CREATE TABLE conference (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(200) NOT NULL,
    start_date   DATE         NOT NULL,
    end_date     DATE         NOT NULL,
    cfp_deadline TIMESTAMPTZ,
    status       VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    CONSTRAINT conference_dates_ordered CHECK (end_date >= start_date),
    CONSTRAINT conference_status_valid CHECK (
        status IN ('DRAFT', 'CALL_OPEN', 'CALL_CLOSED', 'PUBLISHED', 'ARCHIVED')
    )
);

CREATE TABLE room (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conference_id BIGINT       NOT NULL REFERENCES conference (id) ON DELETE CASCADE,
    name          VARCHAR(100) NOT NULL,
    capacity      INTEGER      NOT NULL,
    CONSTRAINT room_capacity_positive CHECK (capacity > 0),
    CONSTRAINT room_name_unique_per_conference UNIQUE (conference_id, name)
);

CREATE TABLE time_slot (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conference_id BIGINT      NOT NULL REFERENCES conference (id) ON DELETE CASCADE,
    starts_at     TIMESTAMPTZ NOT NULL,
    ends_at       TIMESTAMPTZ NOT NULL,
    CONSTRAINT time_slot_ordered CHECK (ends_at > starts_at),
    CONSTRAINT time_slot_unique_per_conference UNIQUE (conference_id, starts_at, ends_at)
);

CREATE TABLE speaker (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   VARCHAR(150) NOT NULL,
    email       VARCHAR(255) NOT NULL UNIQUE,
    affiliation VARCHAR(150),
    bio         TEXT
);

CREATE TABLE session (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conference_id  BIGINT       NOT NULL REFERENCES conference (id) ON DELETE CASCADE,
    title          VARCHAR(200) NOT NULL,
    abstract_text  TEXT         NOT NULL,
    status         VARCHAR(20)  NOT NULL DEFAULT 'PROPOSED',
    track          VARCHAR(100),
    public_summary VARCHAR(400),
    room_id        BIGINT REFERENCES room (id) ON DELETE SET NULL,
    time_slot_id   BIGINT REFERENCES time_slot (id) ON DELETE SET NULL,
    version        BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT session_status_valid CHECK (
        status IN ('PROPOSED', 'ACCEPTED', 'REJECTED', 'SCHEDULED', 'CANCELLED')
    ),
    CONSTRAINT session_scheduled_is_placed CHECK (
        status <> 'SCHEDULED' OR (room_id IS NOT NULL AND time_slot_id IS NOT NULL)
    )
);

-- Partial, so that any number of sessions may sit unscheduled.
CREATE UNIQUE INDEX session_room_not_double_booked
    ON session (room_id, time_slot_id)
    WHERE room_id IS NOT NULL AND time_slot_id IS NOT NULL;

CREATE TABLE session_speaker (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id   BIGINT      NOT NULL REFERENCES session (id) ON DELETE CASCADE,
    speaker_id   BIGINT      NOT NULL REFERENCES speaker (id) ON DELETE CASCADE,
    speaker_role VARCHAR(20) NOT NULL,
    -- Copy of session.time_slot_id: a unique constraint cannot span two tables.
    time_slot_id BIGINT REFERENCES time_slot (id) ON DELETE SET NULL,
    CONSTRAINT session_speaker_unique UNIQUE (session_id, speaker_id),
    CONSTRAINT session_speaker_role_valid CHECK (
        speaker_role IN ('PRESENTER', 'CO_PRESENTER', 'MODERATOR')
    )
);

CREATE UNIQUE INDEX speaker_not_double_booked
    ON session_speaker (speaker_id, time_slot_id)
    WHERE time_slot_id IS NOT NULL;
